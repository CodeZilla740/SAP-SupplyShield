CREATE SCHEMA SUPPLYSHIELD;
SET SCHEMA SUPPLYSHIELD;

CREATE COLUMN TABLE medicines (
  sku          NVARCHAR(20) PRIMARY KEY,
  name         NVARCHAR(80) NOT NULL,
  min_temp     DECIMAL(4,1) NOT NULL,
  max_temp     DECIMAL(4,1) NOT NULL,
  unit         NVARCHAR(10) NOT NULL,
  case_size    INTEGER NOT NULL,
  unit_cost    DECIMAL(9,2),
  batch        NVARCHAR(20),
  manufactured NVARCHAR(10),
  expiry       NVARCHAR(10),
  gdp_class    NVARCHAR(40)
);

CREATE COLUMN TABLE facilities (
  code        NVARCHAR(10) PRIMARY KEY,
  name        NVARCHAR(80) NOT NULL,
  city        NVARCHAR(40),
  type        NVARCHAR(10) NOT NULL,
  priority    NVARCHAR(2),
  ward        NVARCHAR(40),
  storage_loc NVARCHAR(20)
);

CREATE COLUMN TABLE inventory (
  facility_code NVARCHAR(10) NOT NULL REFERENCES facilities(code),
  product_sku   NVARCHAR(20) NOT NULL REFERENCES medicines(sku),
  qty_on_hand   INTEGER NOT NULL,
  reserved_qty  INTEGER NOT NULL DEFAULT 0,
  daily_usage   INTEGER NOT NULL DEFAULT 0,
  safety_stock  INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (facility_code, product_sku)
);

CREATE COLUMN TABLE carriers (
  code                 NVARCHAR(20) PRIMARY KEY,
  name                 NVARCHAR(80) NOT NULL,
  mode                 NVARCHAR(10) NOT NULL,
  cold_chain_certified TINYINT NOT NULL DEFAULT 0,
  min_temp             DECIMAL(4,1),
  max_temp             DECIMAL(4,1),
  base_cost            DECIMAL(9,2) NOT NULL,
  cost_per_km          DECIMAL(7,2) NOT NULL,
  avg_speed_kmh        DECIMAL(6,1) NOT NULL,
  handling_hours       DECIMAL(4,1) NOT NULL,
  telemetry_capable    TINYINT NOT NULL DEFAULT 0,
  vehicle              NVARCHAR(20)
);

CREATE COLUMN TABLE lanes (
  id               INTEGER PRIMARY KEY,
  origin_code      NVARCHAR(10) NOT NULL REFERENCES facilities(code),
  destination_code NVARCHAR(10) NOT NULL REFERENCES facilities(code),
  mode             NVARCHAR(10) NOT NULL,
  distance_km      DECIMAL(8,1) NOT NULL,
  carrier_code     NVARCHAR(20) REFERENCES carriers(code)
);

CREATE COLUMN TABLE purchase_orders (
  ebeln            NVARCHAR(10) PRIMARY KEY,
  supplier_name    NVARCHAR(80),
  product_sku      NVARCHAR(20) NOT NULL REFERENCES medicines(sku),
  destination_code NVARCHAR(10) NOT NULL REFERENCES facilities(code),
  qty              INTEGER NOT NULL,
  port             NVARCHAR(10),
  status           NVARCHAR(20) NOT NULL,
  eta              NVARCHAR(10)
);

CREATE COLUMN TABLE shipments (
  id                NVARCHAR(10) PRIMARY KEY,
  po_ebeln          NVARCHAR(10) REFERENCES purchase_orders(ebeln),
  product_sku       NVARCHAR(20) NOT NULL REFERENCES medicines(sku),
  batch             NVARCHAR(20),
  origin_code       NVARCHAR(10),
  origin_label      NVARCHAR(40),
  destination_code  NVARCHAR(10),
  destination_label NVARCHAR(60),
  route             NVARCHAR(40),
  status            NVARCHAR(20) NOT NULL,
  risk              NVARCHAR(10) NOT NULL,
  delay_hours       DECIMAL(6,1) NOT NULL DEFAULT 0,
  eta_text          NVARCHAR(20),
  current_temp      DECIMAL(4,1)
);

CREATE COLUMN TABLE temperature_readings (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id NVARCHAR(10) NOT NULL REFERENCES shipments(id),
  batch       NVARCHAR(20),
  ts          NVARCHAR(30) NOT NULL,
  temp_c      DECIMAL(4,1) NOT NULL
);

CREATE COLUMN TABLE disruptions (
  id                   NVARCHAR(20) PRIMARY KEY,
  type                 NVARCHAR(30) NOT NULL,
  title                NVARCHAR(120) NOT NULL,
  port                 NVARCHAR(10),
  severity             NVARCHAR(10) NOT NULL,
  description          NVARCHAR(500),
  status               NVARCHAR(20) NOT NULL,
  radius_km            DECIMAL(6,1),
  wind_kmh             DECIMAL(6,1),
  expected_delay_hours DECIMAL(6,1),
  affected_shipments   INTEGER DEFAULT 0,
  affected_pos         INTEGER DEFAULT 0,
  verified             TINYINT NOT NULL DEFAULT 0,
  source               NVARCHAR(120),
  created_at           NVARCHAR(30)
);

CREATE COLUMN TABLE disruption_timeline (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  disruption_id NVARCHAR(20) NOT NULL REFERENCES disruptions(id),
  ts            NVARCHAR(10),
  title         NVARCHAR(80),
  text          NVARCHAR(300),
  state         NVARCHAR(10)
);

CREATE COLUMN TABLE infrastructure_status (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  disruption_id NVARCHAR(20) NOT NULL REFERENCES disruptions(id),
  label         NVARCHAR(60),
  status        NVARCHAR(20),
  tone          NVARCHAR(10),
  icon          NVARCHAR(20)
);

CREATE COLUMN TABLE alerts (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  severity NVARCHAR(10),
  location NVARCHAR(60),
  medicine NVARCHAR(60),
  message  NVARCHAR(200),
  ago      NVARCHAR(20)
);

CREATE COLUMN TABLE recovery_plans (
  id                    NVARCHAR(20) PRIMARY KEY,
  disruption_id         NVARCHAR(20) NOT NULL REFERENCES disruptions(id),
  run_id                NVARCHAR(20) NOT NULL,
  correlation_id        NVARCHAR(20) NOT NULL,
  status                NVARCHAR(20) NOT NULL,
  recommended_option_id NVARCHAR(20),
  score                 DECIMAL(5,1),
  explanation           NCLOB,
  explanation_source    NVARCHAR(200),
  created_at            NVARCHAR(30),
  decided_at            NVARCHAR(30),
  decided_by            NVARCHAR(80),
  decision_comment      NVARCHAR(300)
);

CREATE COLUMN TABLE recovery_options (
  id             NVARCHAR(20) PRIMARY KEY,
  plan_id        NVARCHAR(20) NOT NULL REFERENCES recovery_plans(id),
  code           NVARCHAR(10) NOT NULL,
  title          NVARCHAR(120) NOT NULL,
  source_code    NVARCHAR(10),
  carrier_code   NVARCHAR(20),
  qty            INTEGER DEFAULT 0,
  cost_usd       DECIMAL(9,2) DEFAULT 0,
  eta_hours      DECIMAL(6,1) DEFAULT 0,
  feasible       TINYINT DEFAULT 1,
  compliant      TINYINT DEFAULT 1,
  meets_deadline TINYINT DEFAULT 1,
  eligible       TINYINT DEFAULT 0,
  rank           INTEGER DEFAULT 0,
  recommended    TINYINT DEFAULT 0,
  status         NVARCHAR(20) DEFAULT 'PROPOSED',
  reason         NCLOB,
  checks_json    NCLOB,
  scores_json    NCLOB
);

CREATE COLUMN TABLE approvals (
  id             NVARCHAR(40) PRIMARY KEY,
  plan_id        NVARCHAR(20) NOT NULL REFERENCES recovery_plans(id),
  option_id      NVARCHAR(20) REFERENCES recovery_options(id),
  decision       NVARCHAR(10) NOT NULL,
  actor          NVARCHAR(80) NOT NULL,
  comment        NVARCHAR(300),
  created_at     NVARCHAR(30),
  execution_note NVARCHAR(400)
);

CREATE COLUMN TABLE audit_log (
  seq       INTEGER PRIMARY KEY,
  run_id    NVARCHAR(20),
  ts        NVARCHAR(30) NOT NULL,
  actor     NVARCHAR(40) NOT NULL,
  step      NVARCHAR(120) NOT NULL,
  payload   NCLOB,
  prev_hash NVARCHAR(64) NOT NULL,
  hash      NVARCHAR(64) NOT NULL
);

CREATE COLUMN TABLE pipeline_state (
  name  NVARCHAR(20) PRIMARY KEY,
  value INTEGER NOT NULL
);

