CREATE COLUMN TABLE network_stats (
  metric NVARCHAR(40) PRIMARY KEY,
  value  DECIMAL(10,2) NOT NULL,
  unit   NVARCHAR(10),
  detail NVARCHAR(80)
);

CREATE INDEX idx_temp_shipment ON temperature_readings(shipment_id);
CREATE INDEX idx_options_plan ON recovery_options(plan_id);
CREATE INDEX idx_audit_run ON audit_log(run_id);
